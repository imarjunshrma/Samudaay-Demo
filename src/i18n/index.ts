export type TranslationKey = keyof typeof commonTranslationSource.en;
export type TranslationNamespace = keyof typeof pageTranslations;

function getBundle(language: AppLanguage, namespace?: TranslationNamespace) {
  const common = commonTranslations[language] as TranslationDictionary;
  const page = namespace ? (pageTranslations[namespace]?.[language] as TranslationDictionary | undefined) : undefined;

  return {
    ...common,
    ...(page ?? {}),
  };
}

export function getTranslations(language: AppLanguage, namespace?: TranslationNamespace) {
  return getBundle(language, namespace);
}

export function createTranslator(language: AppLanguage, namespace?: TranslationNamespace) {
  const bundle = getBundle(language, namespace);

  return (
    key: string,
    fallbackOrVars?: string | Record<string, string | number>,
    maybeVars?: Record<string, string | number>,
  ) => {
    const fallback = typeof fallbackOrVars === 'string' ? fallbackOrVars : undefined;
    const vars = (typeof fallbackOrVars === 'string' ? maybeVars : fallbackOrVars) ?? undefined;
    const value = bundle[key] ?? commonTranslations.en[key] ?? fallback ?? key;
    const resolved = typeof value === 'string' ? value : fallback ?? key;

    if (!vars) {
      return resolved;
    }

    return Object.entries(vars).reduce(
      (message, [name, replacement]) =>
        message
          .replace(new RegExp(`\\{${name}\\}`, 'g'), String(replacement))
          .replace(new RegExp(`\\{\\{${name}\\}\\}`, 'g'), String(replacement)),
      resolved,
    );
  };
}

export function translate(language: AppLanguage, key: TranslationKey, namespace?: TranslationNamespace, fallback?: string) {
  const bundle = getBundle(language, namespace);
  const value = bundle[key] ?? commonTranslations.en[key] ?? fallback ?? key;
  return typeof value === 'string' ? value : fallback ?? key;
}
